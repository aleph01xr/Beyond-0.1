export const ALL_STATUS_EFFECTS: StatusEffectMeta[] = [
  ...Object.values(GUARDIAN_STATUS_EFFECTS),
  ...Object.values(COMBAT_STATUS_EFFECTS),
];

export function getStatusEffectMeta(id: string): StatusEffectMeta {
  if (GUARDIAN_STATUS_EFFECTS[id as PlayerStatusType]) {
    return GUARDIAN_STATUS_EFFECTS[id as PlayerStatusType];
  }
  if (COMBAT_STATUS_EFFECTS[id]) {
    return COMBAT_STATUS_EFFECTS[id];
  }
  return {
    id,
    name: id.toUpperCase().replace('_', ' '),
    category: 'combat',
    badge: id.slice(0, 3).toUpperCase(),
    color: '#CBD5E1',
    bgColor: 'bg-slate-900',
    borderColor: 'border-slate-500',
    summary: 'Status affliction affecting combat performance.',
    detailedEffect: 'Combat modifier active on target entity.',
    iconSlotId: `icon_status_${id}`,
  };
}
